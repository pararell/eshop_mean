// PostgreSQL 18 schema (see docs/database.md §1). Migrations are generated from this
// file with `npm run db:generate`; never edit generated migration SQL by hand.
import { sql } from 'drizzle-orm';
import {
  boolean,
  char,
  index,
  integer,
  json,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';
import type { Address, LocalizedCart, ThemeStyles } from '@eshop/shared';

export const langCode = pgEnum('lang_code', ['en', 'sk', 'cs']);
// New values are only ever appended (expand/contract: the previous image must keep working)
export const orderStatus = pgEnum('order_status', [
  'NEW',
  'PAID',
  'SHIPPING',
  'COMPLETED',
  'CANCELED',
  // Card orders (docs/payments.md): created before the customer confirms, then driven by Stripe
  'PENDING_PAYMENT',
  'PAYMENT_FAILED',
  'REFUNDED',
]);

/** uuid primary key generated by PostgreSQL 18's native, time-ordered uuidv7() */
const id = () =>
  uuid('id')
    .primaryKey()
    .default(sql`uuidv7()`);

const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const updatedAt = () =>
  timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow()
    // The database clock, like the insert default (the app and database clocks can differ)
    .$onUpdate(() => sql`now()`);

/** Money in major units (e.g. 19.99), returned to the app as a number (decision D4) */
const money = (name: string) => numeric(name, { precision: 12, scale: 2, mode: 'number' });

const textArray = (name: string) =>
  text(name)
    .array()
    .notNull()
    .default(sql`'{}'::text[]`);

// Users ---------------------------------------------------------------------------------------

export const users = pgTable(
  'users',
  {
    id: id(),
    email: text('email').notNull(),
    /** bcrypt hash (the salt is embedded); null for Google-only accounts */
    passwordHash: text('password_hash'),
    name: text('name'),
    googleId: text('google_id').unique(),
    roles: textArray('roles'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  // One account per email regardless of case (decision D5)
  (t) => [uniqueIndex('users_email_lower_uq').on(sql`lower(${t.email})`)],
);

// Catalog -------------------------------------------------------------------------------------

/** The marked-trail colors a category can follow (tile and menu markers) */
export const trailColor = pgEnum('trail_color', ['red', 'blue', 'green', 'yellow']);

export const categories = pgTable('categories', {
  id: id(),
  titleUrl: text('title_url').notNull().unique(),
  mainImageUrl: text('main_image_url'),
  mainImageName: text('main_image_name'),
  /** Mongoose: mainImage.type (render the image with object-fit: cover) */
  mainImageCover: boolean('main_image_cover').notNull().default(false),
  /** Wide photo for the category page header; null = the main image */
  headerImageUrl: text('header_image_url'),
  /** Null = by position in the category list (red, blue, green, yellow, …) */
  trailColor: trailColor('trail_color'),
  subCategories: textArray('sub_categories'),
  createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const categoryTranslations = pgTable(
  'category_translations',
  {
    categoryId: uuid('category_id')
      .notNull()
      .references(() => categories.id, { onDelete: 'cascade' }),
    lang: langCode('lang').notNull(),
    title: text('title').notNull().default(''),
    description: text('description').notNull().default(''),
    position: integer('position'),
    visibility: boolean('visibility').notNull().default(false),
    menuHidden: boolean('menu_hidden').notNull().default(false),
  },
  (t) => [primaryKey({ columns: [t.categoryId, t.lang] })],
);

export const products = pgTable(
  'products',
  {
    id: id(),
    titleUrl: text('title_url').notNull().unique(),
    mainImageUrl: text('main_image_url'),
    mainImageName: text('main_image_name'),
    images: textArray('images'),
    /** Category title_urls, linked by value (decision D6) */
    tags: textArray('tags'),
    createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('products_tags_gin').using('gin', t.tags), index('products_created_at').on(t.createdAt.desc())],
);

export const productTranslations = pgTable(
  'product_translations',
  {
    productId: uuid('product_id')
      .notNull()
      .references(() => products.id, { onDelete: 'cascade' }),
    lang: langCode('lang').notNull(),
    title: text('title').notNull().default(''),
    description: text('description').notNull().default(''),
    /** HTML fragments from the rich-text editor */
    descriptionFull: textArray('description_full'),
    regularPrice: money('regular_price'),
    salePrice: money('sale_price'),
    onSale: boolean('on_sale').notNull().default(false),
    /** Free text, e.g. 'onStock' (decision D7) */
    stock: text('stock'),
    visibility: boolean('visibility').notNull().default(false),
    shipping: text('shipping').notNull().default('basic'),
    /** <title> of the product page; empty falls back to `title` */
    seoTitle: text('seo_title').notNull().default(''),
    /** <meta name="description">; empty falls back to `description` */
    metaDescription: text('meta_description').notNull().default(''),
  },
  (t) => [
    primaryKey({ columns: [t.productId, t.lang] }),
    // product listing: visible products of a language, sorted by price
    index('product_translations_listing').on(t.lang, t.visibility, t.salePrice),
  ],
);

// Orders --------------------------------------------------------------------------------------

export const orders = pgTable(
  'orders',
  {
    id: id(),
    /** API field `orderId` ('order<ms>t<rand>') */
    orderNumber: text('order_number').notNull().unique(),
    userId: uuid('user_id').references(() => users.id, { onDelete: 'set null' }),
    customerEmail: text('customer_email').notNull(),
    status: orderStatus('status').notNull().default('NEW'),
    /** PAYMENT_ON_DELIVERY | WITH_PAYMENT */
    type: text('type'),
    currency: char('currency', { length: 3 }).notNull(),
    amount: money('amount').notNull(),
    amountRefunded: money('amount_refunded'),
    notes: text('notes'),
    /** Stripe charge id */
    cardId: text('card_id'),
    /** Stripe PaymentIntent of a card order (docs/payments.md) */
    paymentIntentId: text('payment_intent_id').unique(),
    /** API field `outcome.seller_message` */
    sellerMessage: text('seller_message'),
    description: text('description'),
    /** Localized cart snapshot at order time */
    cart: jsonb('cart').$type<LocalizedCart>().notNull(),
    addresses: jsonb('addresses')
      .$type<Address[]>()
      .notNull()
      .default(sql`'[]'::jsonb`),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('orders_user_created').on(t.userId, t.createdAt.desc()), index('orders_created').on(t.createdAt.desc())],
);

// Shop content --------------------------------------------------------------------------------

export const translations = pgTable('translations', {
  lang: langCode('lang').primaryKey(),
  /** { "Key": "Text" } */
  keys: jsonb('keys')
    .$type<Record<string, string>>()
    .notNull()
    .default(sql`'{}'::jsonb`),
  updatedAt: updatedAt(),
});

export const pages = pgTable('pages', {
  id: id(),
  titleUrl: text('title_url').notNull().unique(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const pageTranslations = pgTable(
  'page_translations',
  {
    pageId: uuid('page_id')
      .notNull()
      .references(() => pages.id, { onDelete: 'cascade' }),
    lang: langCode('lang').notNull(),
    title: text('title').notNull().default(''),
    contentHtml: text('content_html').notNull().default(''),
  },
  (t) => [primaryKey({ columns: [t.pageId, t.lang] })],
);

export const themes = pgTable(
  'themes',
  {
    id: id(),
    titleUrl: text('title_url').notNull().unique(),
    active: boolean('active').notNull().default(false),
    styles: jsonb('styles')
      .$type<ThemeStyles>()
      .notNull()
      .default(sql`'{}'::jsonb`),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  // At most one active theme (decision D8); saving must deactivate the others in one transaction
  (t) => [
    uniqueIndex('themes_one_active')
      .on(t.active)
      .where(sql`${t.active}`),
  ],
);

export const configs = pgTable(
  'configs',
  {
    id: id(),
    titleUrl: text('title_url').notNull().unique(),
    active: boolean('active').notNull().default(false),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  // At most one active shop config (decision D8)
  (t) => [
    uniqueIndex('configs_one_active')
      .on(t.active)
      .where(sql`${t.active}`),
  ],
);

export const configShipping = pgTable(
  'config_shipping',
  {
    configId: uuid('config_id')
      .notNull()
      .references(() => configs.id, { onDelete: 'cascade' }),
    lang: langCode('lang').notNull(),
    basicCost: money('basic_cost'),
    basicLimit: money('basic_limit'),
    extendedCost: money('extended_cost'),
    extendedLimit: money('extended_limit'),
  },
  (t) => [primaryKey({ columns: [t.configId, t.lang] })],
);

// Sessions (the table connect-pg-simple expects) ----------------------------------------------

export const session = pgTable(
  'session',
  {
    sid: varchar('sid').primaryKey(),
    sess: json('sess').notNull(),
    expire: timestamp('expire', { precision: 6 }).notNull(),
  },
  (t) => [index('session_expire').on(t.expire)],
);

// AI product drafts (docs/ai.md) -------------------------------------------------------------

export const aiUsageStatus = pgEnum('ai_usage_status', ['ok', 'invalid_output', 'error', 'timeout']);

/** One row per AI request (successful or not): token usage and estimated cost, also used for limits */
export const aiUsage = pgTable(
  'ai_usage',
  {
    id: id(),
    userId: uuid('user_id').references(() => users.id, { onDelete: 'set null' }),
    provider: text('provider').notNull(),
    model: text('model').notNull(),
    imageCount: integer('image_count').notNull().default(0),
    inputTokens: integer('input_tokens').notNull().default(0),
    outputTokens: integer('output_tokens').notNull().default(0),
    /** Estimated from list prices (docs/ai.md); free-tier requests are not actually billed */
    costUsd: numeric('cost_usd', { precision: 12, scale: 6, mode: 'number' }).notNull().default(0),
    durationMs: integer('duration_ms').notNull().default(0),
    status: aiUsageStatus('status').notNull(),
    errorCode: text('error_code'),
    createdAt: createdAt(),
  },
  (t) => [index('ai_usage_user_created').on(t.userId, t.createdAt.desc()), index('ai_usage_created').on(t.createdAt.desc())],
);

